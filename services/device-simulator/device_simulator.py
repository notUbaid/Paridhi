#!/usr/bin/env python3
"""
Paridhi camera device simulator.

Pretends to be an on-site camera: hashes a snapshot (a real image file, or
generated bytes) and reports an incident to the Paridhi API, authenticated with
the shared device token. The server signs what it receives and stores it as
evidence. Uses only the Python standard library.

Usage:
    export PARIDHI_DEVICE_TOKEN=some-long-random-string   # same value the API was started with
    python services/device-simulator/device_simulator.py
    python services/device-simulator/device_simulator.py --snapshot photo.jpg --type VEHICLE_ON_PLOT
"""

import argparse
import hashlib
import json
import os
import sys
import urllib.error
import urllib.request
from datetime import datetime, timezone

INCIDENT_TYPES = [
    "MATERIAL_DUMPING",
    "VEHICLE_ON_PLOT",
    "NEW_STRUCTURE",
    "BOUNDARY_PEG_MOVED",
    "PERSON_ON_PLOT",
    "CAMERA_TAMPER",
    "OTHER",
]


def snapshot_sha256(path):
    """SHA-256 of the snapshot file, or of generated bytes when no file is given."""
    if path:
        with open(path, "rb") as handle:
            return hashlib.sha256(handle.read()).hexdigest()
    synthetic = f"SIMULATED_SNAPSHOT_{datetime.now(timezone.utc).isoformat()}".encode()
    return hashlib.sha256(synthetic).hexdigest()


def report_incident(api_url, token, property_id, incident_type, description, sha256):
    url = f"{api_url.rstrip('/')}/api/properties/{property_id}/incidents"
    body = json.dumps(
        {
            "type": incident_type,
            "description": description,
            "snapshotSha256": sha256,
            "capturedAt": datetime.now(timezone.utc).isoformat(),
        }
    ).encode()
    request = urllib.request.Request(
        url,
        data=body,
        method="POST",
        headers={"Content-Type": "application/json", "Authorization": f"Bearer {token}"},
    )
    with urllib.request.urlopen(request, timeout=10) as response:
        return json.loads(response.read().decode())


def main():
    parser = argparse.ArgumentParser(description="Report a simulated camera incident to the Paridhi API.")
    parser.add_argument("--api-url", default=os.environ.get("PARIDHI_API_URL", "http://localhost:4000"))
    parser.add_argument("--property", default="prop-shamshabad-412", help="Property id, e.g. prop-shamshabad-412")
    parser.add_argument("--type", default="MATERIAL_DUMPING", choices=INCIDENT_TYPES)
    parser.add_argument(
        "--description",
        default="Pile of bricks and gravel near the north-east boundary peg that was not there last week.",
    )
    parser.add_argument("--snapshot", help="Path to an image to hash. Omit to hash generated bytes.")
    args = parser.parse_args()

    token = os.environ.get("PARIDHI_DEVICE_TOKEN")
    if not token:
        sys.exit("Set PARIDHI_DEVICE_TOKEN to the same value the API was started with.")

    sha256 = snapshot_sha256(args.snapshot)
    print(f"Snapshot SHA-256: {sha256}")

    try:
        result = report_incident(args.api_url, token, args.property, args.type, args.description, sha256)
    except urllib.error.HTTPError as error:
        sys.exit(f"API rejected the incident ({error.code}): {error.read().decode()}")
    except urllib.error.URLError as error:
        sys.exit(f"Could not reach the API at {args.api_url}: {error.reason}")

    evidence = result["evidence"]
    print(f"Evidence recorded: {evidence['id']}")
    print(f"Signed payload SHA-256: {evidence['sha256']} (key {evidence['keyId']})")


if __name__ == "__main__":
    main()
